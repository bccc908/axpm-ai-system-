import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import type { FinanceReceipt } from "@/types/finance";
import { buildReceiptDownloadName } from "@/lib/finance/receipt-files";

export async function generateReceiptSummaryPdf(receipt: FinanceReceipt): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const page = doc.addPage([595, 842]);
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const fontBold = await doc.embedFont(StandardFonts.HelveticaBold);

  const left = 50;
  let y = 780;

  function line(text: string, size = 12, bold = false) {
    page.drawText(text, {
      x: left,
      y,
      size,
      font: bold ? fontBold : font,
      color: rgb(0.1, 0.1, 0.1),
    });
    y -= size + 10;
  }

  line("RECEIPT / RESIT", 20, true);
  y -= 8;
  line(`Merchant: ${receipt.merchant ?? "-"}`, 14, true);
  line(
    `Amount: ${receipt.currency ?? "MYR"} ${receipt.amount != null ? receipt.amount.toFixed(2) : "-"}`,
    14,
    true,
  );
  if (receipt.receipt_date) {
    line(`Date: ${receipt.receipt_date}`, 12);
  }
  if (receipt.notes) {
    y -= 4;
    line("Notes:", 12, true);
    for (const chunk of wrapText(toAsciiNotes(receipt.notes), 70)) {
      line(chunk, 11);
    }
  }
  if (receipt.category) {
    line(`Category: ${receipt.category}`, 11);
  }

  y -= 20;
  line("Generated by AXPM Finance", 9);
  line(`Receipt ID: ${receipt.id}`, 9);

  return doc.save();
}

function wrapText(text: string, maxLen: number): string[] {
  const words = text.split(/\s+/);
  const lines: string[] = [];
  let current = "";
  for (const word of words) {
    const next = current ? `${current} ${word}` : word;
    if (next.length > maxLen) {
      if (current) lines.push(current);
      current = word;
    } else {
      current = next;
    }
  }
  if (current) lines.push(current);
  return lines;
}

function toAsciiNotes(notes: string): string {
  return notes
    .replace(/全季酒店 济南西站东广场店/g, "Ji Hotel Jinan West Station")
    .replace(/[^\x20-\x7E]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function receiptSummaryDownloadName(receipt: FinanceReceipt): string {
  const base = buildReceiptDownloadName(receipt).replace(/\.pdf$/i, "");
  return `${base}_summary.pdf`;
}
